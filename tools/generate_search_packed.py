#!/usr/bin/env python3
"""Losslessly pack the pinned search codepoint/group index for Pico.

SPDX-License-Identifier: Apache-2.0
The original generated pypinyin table remains the authoritative source.
"""
from pathlib import Path
import argparse,re,hashlib
ROOT=Path(__file__).resolve().parents[1]
def values(source,name):
    match=re.search(r'\b'+name+r'\[\]\s*=\s*\{(.*?)\};',source,re.S)
    assert match,name
    return [int(x) for x in re.findall(r'\d+',match[1])]
def packed(values,bits):
    assert 1<=bits<=24
    data=bytearray((len(values)*bits+7)//8+3)
    for i,value in enumerate(values):
        assert 0<=value<(1<<bits)
        offset,shift=divmod(i*bits,8)
        word=value<<shift
        for n in range(4):
            if offset+n<len(data):data[offset+n]|=(word>>(n*8))&255
    return bytes(data)
def generate(table):
    source=table.read_text();cps=values(source,'search_codepoints');groups=values(source,'search_groups')
    assert len(cps)==len(groups) and cps==sorted(set(cps)) and max(cps)<=0x10ffff
    result='''/* SPDX-License-Identifier: MIT
 * Generated by tools/generate_search_packed.py; do not hand-edit.
 * Lossless encoding of search_table.h (pypinyin); original license: LICENSE.pypinyin.
 * Three sentinel bytes allow bounded four-byte reads without runtime allocation.
 */
#pragma once
'''
    result+='#define SEARCH_PACKED_COUNT '+str(len(cps))+'u\n'
    result+='// Source SHA256: '+hashlib.sha256(table.read_bytes()).hexdigest()+'\n'
    for name,items in [('codepoints',cps),('groups',groups)]:
        bits=max(items).bit_length();data=packed(items,bits)
        result+='#define SEARCH_PACKED_'+name.upper()+'_BITS '+str(bits)+'u\n'
        result+='static const uint8_t search_packed_'+name+'[] = {\n'
        result+=''.join('    '+','.join('0x%02x'%x for x in data[i:i+24])+',\n' for i in range(0,len(data),24))
        result+='};\n'
    return result
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--root',type=Path,default=ROOT);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    folder=args.root/'components/read_pico_search';expected=generate(folder/'search_table.h');path=folder/'search_packed.h'
    if args.check:assert path.read_text()==expected,'Run tools/generate_search_packed.py'
    else:path.write_text(expected)
    print('PASS: reproducible lossless search index' if args.check else 'Generated lossless Pico search index')
