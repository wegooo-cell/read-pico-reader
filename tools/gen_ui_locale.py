"""生成只读系统文案表，检查完整覆盖和printf签名。 / Generate readonly UI literals with coverage and printf validation."""
from pathlib import Path
import ast,json,re,argparse
ROOT=Path(__file__).resolve().parents[1]
CATALOG=ROOT/'components/kiiko_locale/locales/en.json'
TOKEN=re.compile(r"//[^\n]*|/\*[\s\S]*?\*/|'(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"")
CJK=re.compile('[\u4e00-\u9fff]')
PRINTF=re.compile(r'%(?:\d+\$)?[-+#0 \']*(?:\d+|\*(?:\d+\$)?)?(?:\.(?:\d+|\*(?:\d+\$)?))?(?:hh|ll|[hljztL])?[diouxXfFeEgGaAcspn%]')
def signature(text):
 return [(m[0],m[0].count('*')) for m in PRINTF.finditer(text) if m[0]!='%%']
def paths():
 result=[]
 for directory in ['main/apps','main/ui','boards/pico/src/main/apps','boards/pico/src/main/ui']:
  for p in sorted((ROOT/directory).glob('*.c')):
   if p.name.startswith('app_') and p.name not in ['app_book.c','app_files.c','app_dashboard.c','app_device_settings.c','app_image.c','app_transfer.c','app_boot_recovery.c','app_onboarding.c']:continue
   if p.name in ['ui_ime.c','ui_hanzi.c']:continue
   result.append(p)
 for f in ['main/apps/book_manage_ui.h','main/lock_screen.c','boards/pico/src/main/lock_screen.c','main/ota_online.c','main/ota_update.c','main/ota_release.c','main/settings.c','boards/pico/src/main/settings.c','main/factory_reset.c','boards/metalio47/src/main/time_service.c','main/time_service.c','boards/pico/src/main/time_service.c','main/font/online_font.c','main/app/sd_recovery.c','main/app/app_loop.c','boards/pico/src/main/app/app_loop.c','components/read_pico_transfer/read_pico_transfer.c','boards/pico/src/components/read_pico_transfer/read_pico_transfer.c']:
  p=ROOT/f
  if p.exists():result.append(p)
 return result

def literals(text):
 result=[];previous=None;span_end=0
 for token in TOKEN.finditer(text):
  if not token[0].startswith('"'):continue
  value=ast.literal_eval(token[0]);gap=TOKEN.sub(lambda m:'' if not m[0].startswith('"') else m[0],text[span_end:token.start()])
  if previous is not None and not gap.strip():result[-1]+=value
  else:result.append(value)
  previous=value;span_end=token.end()
 return result

def collect():
 found={}
 for path in paths()+[ROOT/p for p in ['boards/metalio47/src/main/sleep.c','boards/pico/src/main/sleep.c','boards/metalio47/src/main/app_main.c','boards/pico/src/main/app_main.c'] if (ROOT/p).exists()]:
  for text in literals(path.read_text()):
   if CJK.search(text):found.setdefault(text,[]).append(str(path.relative_to(ROOT)))
 return found

def main():
 p=argparse.ArgumentParser();p.add_argument('--collect',type=Path);args=p.parse_args();found=collect()
 if args.collect:
  args.collect.write_text(json.dumps(found,indent=2,ensure_ascii=False)+'\n');print(len(found));return
 data=json.loads(CATALOG.read_text());missing=sorted(set(found)-set(data));assert not missing,'Untranslated UI literals: '+repr(missing)
 preserved=set(json.loads((CATALOG.parent/'preserved-content.json').read_text()))
 for zh,en in data.items():
  assert en and (not CJK.search(en) or (zh in preserved and zh==en)),(zh,en)
  assert signature(zh)==signature(en),(zh,en,signature(zh),signature(en))
 rows=['/* Generated by tools/gen_ui_locale.py; do not edit. */','static const ui_locale_pair_t s_pairs[] = {']
 for zh,en in sorted(data.items()):rows.append('    {'+json.dumps(zh,ensure_ascii=False)+','+json.dumps(en,ensure_ascii=False)+'},')
 rows.append('};\n');(CATALOG.parent.parent/'ui_locale_catalog.inc').write_text('\n'.join(rows));print(f'{len(data)} UI translations validated and generated')
if __name__=='__main__':main()
